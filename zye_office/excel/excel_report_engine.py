"""
Automated Report Generation & KPI Dashboard Engine for Microsoft Excel — Zye Day 22.
Builds executive monthly sales, financial, and KPI dashboard reports with charts and KPIs.
"""

from __future__ import annotations

import datetime
import logging
from typing import Any, Dict, List, Optional, Union
from zye_office.excel.excel_adapter import ExcelAdapter
from zye_office.excel.excel_chart_engine import ExcelChartEngine
from zye_office.excel.excel_conditional_formatting import ExcelConditionalFormattingEngine
from zye_office.excel.excel_formatting_engine import ExcelFormattingEngine
from zye_office.excel.excel_range_engine import ExcelRangeEngine
from zye_office.excel.excel_validator import ExcelValidator
from zye_office.excel.excel_worksheet_manager import ExcelWorksheetManager
from zye_office.models.excel_models import (
    ExcelChartConfig,
    ExcelFormatOptions,
    ExcelReportConfig,
)

logger = logging.getLogger("zye.office.excel.report")


class ExcelReportEngine:
    """Generates structured enterprise reports, KPI dashboards, and executive summaries."""

    def __init__(
        self,
        adapter: Optional[ExcelAdapter] = None,
        worksheet_manager: Optional[ExcelWorksheetManager] = None,
        range_engine: Optional[ExcelRangeEngine] = None,
        formatting_engine: Optional[ExcelFormattingEngine] = None,
        chart_engine: Optional[ExcelChartEngine] = None,
        cf_engine: Optional[ExcelConditionalFormattingEngine] = None,
        validator: Optional[ExcelValidator] = None,
    ) -> None:
        self.adapter = adapter or ExcelAdapter()
        self.worksheet_manager = worksheet_manager or ExcelWorksheetManager(self.adapter)
        self.range_engine = range_engine or ExcelRangeEngine(self.adapter)
        self.formatting_engine = formatting_engine or ExcelFormattingEngine(self.adapter)
        self.chart_engine = chart_engine or ExcelChartEngine(self.adapter)
        self.cf_engine = cf_engine or ExcelConditionalFormattingEngine(self.adapter)
        self.validator = validator or ExcelValidator()

    def generate_sales_report(
        self,
        title: str = "Monthly Sales Executive Report",
        period: str = "Q4 2026",
        sheet_name: str = "Sales_Report",
    ) -> Dict[str, Any]:
        """Generate a complete sales report with KPI cards, data matrix, totals, and a column chart."""
        # 1. Create dedicated report worksheet
        ws_res = self.worksheet_manager.create_worksheet(name=sheet_name)
        active_sheet = ws_res.get("sheet_name", sheet_name)

        # 2. Header Block
        now_str = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
        header_matrix = [
            [title, "", "", ""],
            [f"Reporting Period: {period} | Generated by Zye AI on {now_str}", "", "", ""],
            ["", "", "", ""],
        ]
        self.range_engine.set_range_values("A1:D3", header_matrix)
        self.formatting_engine.format_range(
            "A1:D1",
            ExcelFormatOptions(font_name="Calibri", font_size=16.0, bold=True, color=16711680),
        )
        self.formatting_engine.format_range(
            "A2:D2",
            ExcelFormatOptions(font_name="Calibri", font_size=10.0, italic=True),
        )

        # 3. KPI Cards Block
        kpi_matrix = [
            ["Metric", "Target", "Actual", "Variance"],
            ["Total Revenue", "$150,000", "$168,500", "+12.3%"],
            ["Units Sold", "1,200", "1,340", "+11.6%"],
            ["Gross Margin", "45.0%", "47.2%", "+2.2%"],
        ]
        self.range_engine.set_range_values("A4:D7", kpi_matrix)
        self.formatting_engine.format_range(
            "A4:D4",
            ExcelFormatOptions(font_name="Calibri", font_size=11.0, bold=True, bg_color=12566463, borders="thin"),
        )
        self.formatting_engine.format_range(
            "A5:D7",
            ExcelFormatOptions(font_name="Calibri", font_size=10.0, borders="thin"),
        )

        # 4. Regional Sales Breakdown Table
        breakdown_matrix = [
            ["Region", "Q1 Sales", "Q2 Sales", "Q3 Sales", "Q4 Sales"],
            ["North America", 45000, 48000, 52000, 58000],
            ["Europe", 32000, 35000, 38000, 41000],
            ["Asia-Pacific", 28000, 31000, 36000, 42000],
            ["Latin America", 15000, 16500, 18000, 20500],
            ["Total", "=SUM(B10:B13)", "=SUM(C10:C13)", "=SUM(D10:D13)", "=SUM(E10:E13)"],
        ]
        self.range_engine.set_range_values("A9:E14", breakdown_matrix)
        self.formatting_engine.format_range(
            "A9:E9",
            ExcelFormatOptions(font_name="Calibri", font_size=11.0, bold=True, bg_color=14277081, borders="thin"),
        )
        self.formatting_engine.format_range(
            "B10:E14",
            ExcelFormatOptions(number_format="$#,##0", borders="thin"),
        )
        self.formatting_engine.format_range(
            "A14:E14",
            ExcelFormatOptions(bold=True, borders="thin", bg_color=15395562),
        )

        # 5. Conditional Formatting on Regional Sales
        self.cf_engine.add_color_scale_rule("B10:E13")

        # 6. Chart Creation
        chart_res = self.chart_engine.create_chart(
            ExcelChartConfig(
                chart_type="CLUSTERED_COLUMN",
                source_range="A9:E13",
                title="2026 Regional Sales Quarterly Performance",
                x_title="Region",
                y_title="Revenue (USD)",
                left_points=350.0,
                top_points=80.0,
                width_points=420.0,
                height_points=240.0,
            )
        )

        # 7. Autofit Columns
        self.formatting_engine.autofit_columns()

        return {
            "status": "SUCCESS",
            "report_type": "MONTHLY_SALES",
            "sheet_name": active_sheet,
            "chart_created": chart_res.get("status") == "SUCCESS",
            "kpis_included": 3,
        }

    def generate_kpi_dashboard(
        self,
        title: str = "Enterprise KPI Operational Dashboard",
        sheet_name: str = "KPI_Dashboard",
    ) -> Dict[str, Any]:
        """Generate high-level KPI dashboard."""
        ws_res = self.worksheet_manager.create_worksheet(name=sheet_name)
        active_sheet = ws_res.get("sheet_name", sheet_name)

        header = [
            [title, "", ""],
            ["Operational Health & Performance Index", "", ""],
            ["", "", ""],
        ]
        self.range_engine.set_range_values("A1:C3", header)
        self.formatting_engine.format_range("A1:C1", ExcelFormatOptions(font_name="Segoe UI", font_size=16.0, bold=True))

        kpis = [
            ["KPI Indicator", "Score", "Benchmark"],
            ["System Reliability", "99.98%", "99.90%"],
            ["Customer Satisfaction", "94.5%", "90.0%"],
            ["Automation Efficiency", "88.2%", "80.0%"],
            ["Incident Resolution Time", "14 min", "20 min"],
        ]
        self.range_engine.set_range_values("A4:C8", kpis)
        self.formatting_engine.apply_preset("A4:C8", "KPI_DASHBOARD")
        self.formatting_engine.autofit_columns()

        return {
            "status": "SUCCESS",
            "dashboard_type": "KPI_DASHBOARD",
            "sheet_name": active_sheet,
        }
