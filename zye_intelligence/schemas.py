"""
Structured Pydantic Schemas for Zye Day 13 Autonomous Intelligence System.
Defines models for Negative Pre-Mortem Audits, Multi-Solution Decision Matrix,
Dynamic Mission Profiles, Autonomous Problem Detection, and Emergency Reflexes.
"""

from __future__ import annotations

import math
from datetime import datetime, timezone
from typing import Any, Literal
from pydantic import BaseModel, Field, field_validator


class NegativeAuditReport(BaseModel):
    """
    Structured pre-mortem audit report generated by the 100% Negative Pre-Mortem Brain.
    Combines core source-compatible fields with Day 13 extended audit fields.
    """

    # --- Core 5 source-compatible field names (Section 05) ---
    overall_failure_risk: Literal["LOW", "MEDIUM", "HIGH", "CRITICAL"] = Field(
        ..., description="Adversarial failure risk classification: LOW, MEDIUM, HIGH, or CRITICAL"
    )
    predicted_problems: list[str] = Field(
        default_factory=list, description="Plausible failure modes identified via FMEA"
    )
    hidden_assumptions_broken: list[str] = Field(
        default_factory=list, description="Hidden assumptions challenged and falsified"
    )
    corrected_hardened_steps: list[str] = Field(
        default_factory=list, description="Actionable hardened execution plan with mitigations"
    )
    requires_user_confirmation: bool = Field(
        ..., description="Whether explicit human confirmation is mandatory before execution"
    )

    # --- Section 05 extended fields ---
    risk_rationale: str = Field(
        default="", description="Detailed engineering rationale justifying the assigned risk level"
    )
    evidence: list[str] = Field(
        default_factory=list, description="Confirmed facts and observable evidence underpinning the audit"
    )
    affected_resources: list[str] = Field(
        default_factory=list, description="Target files, processes, devices, or APIs potentially impacted"
    )
    mitigation_actions: list[str] = Field(
        default_factory=list, description="Specific defensive measures applied to counteract identified problems"
    )
    residual_risks: list[str] = Field(
        default_factory=list, description="Remaining unmitigated risks or irreducible uncertainties"
    )
    rollback_plan: list[str] = Field(
        default_factory=list, description="Deterministic recovery steps if execution encounters failure"
    )
    verification_steps: list[str] = Field(
        default_factory=list, description="Post-execution inspection checks to confirm success"
    )
    required_permissions: list[str] = Field(
        default_factory=list, description="Operating system privileges or tokens required for safe execution"
    )
    missing_information: list[str] = Field(
        default_factory=list, description="Information gaps, unknown states, or missing telemetry"
    )
    audit_timestamp: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat(),
        description="ISO 8601 UTC timestamp of audit generation",
    )
    mission_mode: str = Field(
        default="NORMAL_ASSISTANT", description="Active mission profile during audit generation"
    )
    audit_version: str = Field(
        default="1.0.0", description="Schema version of the Negative Audit Report"
    )

    # --- Backward compatibility handles ---
    confirmation_reason: str = Field(
        default="", description="Detailed rationale for requiring confirmation"
    )
    preflight_summary: dict[str, Any] = Field(
        default_factory=dict, description="Live system preflight snapshot"
    )
    recommended_execution_strategy: str = Field(
        default="Proceed with hardened steps",
        description="Recommended strategy or abort decision",
    )
    model_name: str = Field(
        default="gemini-2.5-flash", description="Model generating the adversarial audit"
    )

    @field_validator(
        "predicted_problems",
        "hidden_assumptions_broken",
        "corrected_hardened_steps",
        "evidence",
        "affected_resources",
        "mitigation_actions",
        "residual_risks",
        "rollback_plan",
        "verification_steps",
        "required_permissions",
        "missing_information",
        mode="before",
    )
    @classmethod
    def validate_string_list(cls, v: Any) -> list[str]:
        if not isinstance(v, list):
            if isinstance(v, str):
                return [v]
            return []
        return [str(item) for item in v]


class SolutionCandidate(BaseModel):
    """Candidate solution for Multi-Solution Decision Matrix."""

    name: str = Field(..., description="Unique name of the candidate solution")
    description: str = Field(..., description="Summary of approach and mechanics")
    reliability: float = Field(..., ge=1.0, le=10.0, description="Score 1.0 to 10.0")
    speed: float = Field(..., ge=1.0, le=10.0, description="Score 1.0 to 10.0")
    safety: float = Field(..., ge=1.0, le=10.0, description="Score 1.0 to 10.0")
    simplicity: float = Field(..., ge=1.0, le=10.0, description="Score 1.0 to 10.0")
    rationale: str = Field(default="", description="Justification for estimated scores")
    pros: list[str] = Field(default_factory=list, description="Advantages of this candidate")
    cons: list[str] = Field(default_factory=list, description="Disadvantages or risks")
    resource_requirements: str = Field(default="", description="Estimated memory/CPU/disk impact")

    @field_validator("reliability", "speed", "safety", "simplicity")
    @classmethod
    def validate_finite_score(cls, v: float) -> float:
        if math.isnan(v) or math.isinf(v):
            raise ValueError("Candidate score must be a finite number between 1.0 and 10.0")
        if not (1.0 <= v <= 10.0):
            raise ValueError(f"Score must be between 1.0 and 10.0, got {v}")
        return float(v)


