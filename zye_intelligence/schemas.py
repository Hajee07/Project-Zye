    safety_scores: dict[str, float] = Field(default_factory=dict)
    simplicity_scores: dict[str, float] = Field(default_factory=dict)
    pros: dict[str, list[str]] = Field(default_factory=dict)
    cons: dict[str, list[str]] = Field(default_factory=dict)
    resource_requirements: dict[str, str] = Field(default_factory=dict)
    risk_analysis: dict[str, Any] = Field(default_factory=dict)
    recommended_best_solution: dict[str, Any] = Field(default_factory=dict)
    full_comparison_ranking: list[dict[str, Any]] = Field(default_factory=list)
    recommendation_reason: str = ""
    unresolved_uncertainties: list[str] = Field(default_factory=list)
    tradeoffs: list[str] = Field(default_factory=list)


