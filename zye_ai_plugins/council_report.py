"""Comprehensive Decision Report Generator for Zye AI Council.

Formats, serializes, and persists full multi-model deliberation records:
- Formats: JSON, Markdown, Plain Text
- Structure: Question, Participants, Independent Answers, Disagreements, Consensus,
             Decision Matrix, Evidence Tiers, and Gemini Final Verdict.
"""

from __future__ import annotations

import json
import logging
import os
import time
from pathlib import Path
from typing import Any, Dict, List, Optional, Union

logger = logging.getLogger("zye.ai_plugins.report")


def generate_markdown_report(session: Dict[str, Any]) -> str:
    """Generate a clean, professional GitHub-flavored Markdown report."""
    cid = session.get("council_id", "council_unknown")
    q = session.get("question", "")
    mode = session.get("mode", "QUICK").upper()
    status = session.get("status", "COMPLETED")
    verdict = session.get("final_decision", {})

    lines = [
        f"# ZYE AI COUNCIL DELIBERATION REPORT",
        f"**Session ID:** `{cid}`  ",
        f"**Operating Mode:** `{mode}` | **Status:** `{status}` | **Date:** `{time.strftime('%Y-%m-%d %H:%M:%S')}`  ",
        f"**Supreme Arbiter:** Google Gemini Master Brain (Voice: `en-IN-NeerjaNeural`)  ",
        "",
        "---",
        "",
        f"## 1. Problem Statement",
        f"> {q}",
        "",
        f"## 2. Council Participants",
    ]

    participants = session.get("participants", [])
    for p in participants:
        status_tag = "READY" if p.get("status") == "success" else "ERROR"
        lines.append(f"- **{p.get('provider_id', '').upper()}** (`{p.get('model', 'default')}`) — Status: `[{status_tag}]` | Latency: `{p.get('latency_ms', 0)}ms`")

    lines.append("")
    lines.append("## 3. Disagreement & Consensus Summary")
    consensus = session.get("consensus", {})
    lines.append(f"- **Consensus Status:** `{consensus.get('consensus_status', 'UNKNOWN')}` (Alignment Score: `{consensus.get('agreement_score', 0.0)}`)")
    
    shared = consensus.get("shared_points", [])
    if shared:
        lines.append("\n### Shared Agreements")
        for s in shared[:5]:
            lines.append(f"- [{s.get('consensus_level')}] **{s.get('topic').title()}:** {s.get('summary')}")

    disagreements = session.get("comparison", {}).get("disagreements", [])
    if disagreements:
        lines.append("\n### Key Disagreements & Conflicts")
        for d in disagreements[:6]:
            lines.append(f"- **[{d.get('severity')}] {d.get('category')} ({d.get('topic')}):** {d.get('explanation')}")
            lines.append(f"  - *{d.get('provider_a')}:* {d.get('position_a')}")
            lines.append(f"  - *{d.get('provider_b')}:* {d.get('position_b')}")

    # Decision Ranking
    evaluation = session.get("evaluation", {})
    ranked = evaluation.get("ranked_solutions", [])
    if ranked:
        lines.append("")
        lines.append(f"## 4. Multi-Criteria Decision Ranking (Priority: `{evaluation.get('priority_mode', 'BALANCED')}`)")
        for r in ranked:
            lines.append(f"{r.get('rank')}. **{r.get('title')}** (Score: `{r.get('composite_score')}`) — Proposed by: `{r.get('provider_id')}`")
            if r.get("pros"):
                lines.append(f"   - **Pros:** {', '.join(r.get('pros')[:3])}")
            if r.get("cons"):
                lines.append(f"   - **Cons:** {', '.join(r.get('cons')[:2])}")

    # Gemini Supreme Verdict
    lines.append("")
    lines.append("## 5. Gemini Master Brain Final Verdict")
    lines.append(f"- **Verdict Category:** `{verdict.get('verdict_category', 'HYBRID_SOLUTION')}`")
    lines.append(f"- **Recommended Path:** `{verdict.get('selected_solution', 'Synthesized Recommendation')}`")
    lines.append("")
    lines.append("### Executive Reasoning")
    for r in verdict.get("reasoning", []):
        lines.append(f"- {r}")

    if verdict.get("unresolved_risks"):
        lines.append("\n### Remaining Risks & Caveats")
        for risk in verdict.get("unresolved_risks", []):
            lines.append(f"- ⚠️ {risk}")

    lines.append("")
    lines.append("---")
    lines.append("*Report generated by Zye AI Hybrid Assistant Multi-AI Council Engine.*")
    return "\n".join(lines)


def generate_ai_council_report(
    session_data: Dict[str, Any],
    format: str = "json",
) -> Union[Dict[str, Any], str]:
    """Format Council session data into structured JSON or Markdown."""
    if format.lower() == "markdown":
        return generate_markdown_report(session_data)
    elif format.lower() == "text":
        md = generate_markdown_report(session_data)
        # Strip simple markdown characters for plain text
        return md.replace("`", "").replace("**", "").replace("## ", "").replace("# ", "")
    return session_data


def save_ai_council_report(
    session_data: Dict[str, Any],
    save_dir: Optional[Path] = None,
) -> Dict[str, Any]:
    """Persist Council report as JSON and Markdown in reports directory."""
    target_dir = save_dir or (Path(__file__).resolve().parent.parent / "reports")
    target_dir.mkdir(parents=True, exist_ok=True)

    cid = session_data.get("council_id", f"council_{int(time.time())}")
    json_path = target_dir / f"{cid}.json"
    md_path = target_dir / f"{cid}.md"

    try:
        with open(json_path, "w", encoding="utf-8") as f:
            json.dump(session_data, f, indent=2)

        md_content = generate_markdown_report(session_data)
        with open(md_path, "w", encoding="utf-8") as f:
            f.write(md_content)

        return {
            "success": True,
            "council_id": cid,
            "json_path": str(json_path),
            "markdown_path": str(md_path),
        }
    except Exception as exc:
        logger.exception("Failed saving Council report: %s", exc)
        return {"success": False, "error": str(exc), "council_id": cid}
